#!/usr/bin/env python3
"""Generate src/strata/assets.c and assets_list.h from the pixel sources in src/strata/assets/.

  icons.txt      icons as text, one character per pixel
  font.txt       the layer-name font, same format (made by tools/strata-gen-font.py)

Everything is 1 bit per pixel and is drawn to the screen pixel for pixel; nothing
is scaled or smoothed. Run this after editing either file:

  tools/strata-gen-assets.py

Vendored from nice-view-strata's scripts/gen_assets.py; the font is a Kibård
addition (see src/strata/README.md).
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "src" / "strata"
ASSETS = ROOT / "assets"


def pack(rows, width):
    """Rows of '#'/'.' to bytes, MSB = leftmost pixel, each row padded to a byte."""
    out = []
    for row in rows:
        row = row.ljust(width, ".")
        for i in range(0, width, 8):
            bits = row[i : i + 8].ljust(8, ".")
            out.append(sum(1 << (7 - b) for b, c in enumerate(bits) if c == "#"))
    return out


def c_array(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def is_comment(line):
    return not line or line.startswith("#") and not set(line) <= {"#", "."}


def read_icons(path):
    icons, name = {}, None
    for line in path.read_text().splitlines():
        line = line.strip()
        if is_comment(line):
            continue
        if line.startswith("icon "):
            name = line.split()[1]
            icons[name] = []
        elif name is not None:
            if set(line) - {"#", "."}:
                raise SystemExit(f"{path}: bad row in icon {name}: {line!r}")
            icons[name].append(line)
    for name, rows in icons.items():
        if not rows or len({len(r) for r in rows}) != 1:
            raise SystemExit(f"{path}: icon {name} has rows of different widths")
    return icons


def read_font(path):
    """Returns (height, [(codepoint, left, advance, rows)]) sorted by codepoint."""
    height, glyphs = None, []
    for line in path.read_text().splitlines():
        line = line.strip()
        if is_comment(line):
            continue
        if line.startswith("font "):
            height = int(line.split()[1])
        elif line.startswith("glyph "):
            _, cp, left, advance = line.split()[:4]
            # Advance in 1/16 px.
            glyphs.append((int(cp.removeprefix("U+"), 16), int(left), round(float(advance) * 16), []))
        elif glyphs:
            if set(line) - {"#", "."}:
                raise SystemExit(f"{path}: bad row in glyph U+{glyphs[-1][0]:04X}: {line!r}")
            glyphs[-1][3].append(line)
    if height is None:
        raise SystemExit(f"{path}: no 'font <height>' line")
    for cp, _, _, rows in glyphs:
        if len(rows) != height or len({len(r) for r in rows}) != 1:
            raise SystemExit(f"{path}: glyph U+{cp:04X} must be {height} rows of equal width")
    if len({g[0] for g in glyphs}) != len(glyphs):
        raise SystemExit(f"{path}: a glyph is defined twice")
    return height, sorted(glyphs)


def main():
    out = [
        "/* Generated by tools/strata-gen-assets.py. Do not edit; edit the",
        " * sources in src/strata/assets/ and run the script again. */",
        "",
        '#include "assets.h"',
        "",
    ]

    for name, rows in read_icons(ASSETS / "icons.txt").items():
        w, h = len(rows[0]), len(rows)
        out += [
            c_array(f"icon_{name}_data", pack(rows, w)),
            f"const struct sv_icon sv_icon_{name} = {{{w}, {h}, icon_{name}_data}};",
            "",
        ]

    height, glyphs = read_font(ASSETS / "font.txt")
    data, entries = [], []
    for cp, left, advance, rows in glyphs:
        w = len(rows[0])
        entries.append(f"    {{0x{cp:04x}, {left}, {advance}, {w}, {len(data)}}},")
        data += pack(rows, w)
    out += [
        c_array("font_data", data),
        "",
        "static const struct sv_glyph font_glyphs[] = {",
        *entries,
        "};",
        f"const struct sv_font sv_font_name = {{{height}, {len(glyphs)}, font_glyphs, font_data}};",
        "",
    ]

    (ROOT / "assets.c").write_text("\n".join(out))

    externs = re.findall(r"^const (struct sv_\w+ sv_\w+)", "\n".join(out), re.M)
    (ROOT / "assets_list.h").write_text(
        "/* Generated by tools/strata-gen-assets.py. Do not edit. */\n\n"
        + "".join(f"extern const {e};\n" for e in externs)
    )


if __name__ == "__main__":
    main()
